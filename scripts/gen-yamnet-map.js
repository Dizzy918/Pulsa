#!/usr/bin/env node
/**
 * Generates the AudioSet(521-class) → Tactiq(8-category) mapping from
 * scripts/yamnet_class_map.csv into:
 *   - lib/yamnetMap.ts                            (phone app, index-based)
 *   - android/wear/src/main/java/com/tactiq/wear/YamnetMap.kt (watch app, label-based)
 *
 * Run `npm run gen:yamnet-map` after editing the rules below.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const csv = fs.readFileSync(path.join(__dirname, "yamnet_class_map.csv"), "utf8");

// index,mid,display_name — display_name may be quoted and contain commas.
const rows = csv
  .trim()
  .split("\n")
  .map((line) => line.replace(/\r$/, ""))
  .slice(1)
  .map((line) => {
    const m = line.match(/^(\d+),([^,]+),(?:"(.*)"|(.*))$/);
    if (!m) throw new Error(`Unparseable row: ${line}`);
    return { index: Number(m[1]), name: m[3] ?? m[4] };
  });

// AudioSet ordering: indices 132..276 are the music/instrument/genre block.
const MUSIC_RANGE = [132, 276];

// First matching rule wins. Keywords are lowercase substring matches.
const RULES = [
  {
    category: "alarm",
    keywords: [
      "siren", "alarm", "smoke detector", "buzzer", "civil defense",
      "air horn", "vehicle horn", "car horn", "honking", "toot",
      "reversing beeps", "train horn", "emergency vehicle", "foghorn",
      "steam whistle", "screaming",
    ],
    exclude: ["toothbrush"],
  },
  {
    category: "baby_cry",
    keywords: ["baby cry", "infant cry", "crying, sobbing", "whimper"],
    exclude: ["whimper (dog)"],
  },
  {
    category: "dog_bark",
    keywords: ["dog", "bark", "bow-wow", "howl", "yip", "growling", "whimper (dog)"],
  },
  {
    category: "doorbell",
    keywords: [
      "doorbell", "ding-dong", "knock", "telephone bell ringing",
      "telephone", "ringtone", "beep, bleep", "bicycle bell", "church bell",
    ],
    exclude: ["engine knocking"],
  },
  {
    category: "loud_noise",
    keywords: [
      "explosion", "gunshot", "fireworks", "firecracker", "boom", "bang",
      "smash, crash", "breaking", "shatter", "glass", "thunder", "slam",
      "skidding", "tire squeal", "screech",
    ],
  },
  {
    category: "speech",
    keywords: [
      "speech", "conversation", "narration", "babbling", "shout", "bellow",
      "whoop", "yell", "children shouting", "battle cry",
    ],
  },
  {
    category: "music",
    keywords: ["singing", "choir", "yodeling", "chant", "humming", "whistling", "rapping"],
  },
];

function categorize(row) {
  if (row.index >= MUSIC_RANGE[0] && row.index <= MUSIC_RANGE[1]) return "music";
  const name = row.name.toLowerCase();
  for (const rule of RULES) {
    if (rule.exclude && rule.exclude.some((k) => name.includes(k))) continue;
    if (rule.keywords.some((k) => name.includes(k))) return rule.category;
  }
  return null; // ambient / not alert-worthy
}

const mapped = rows.map((r) => ({ ...r, category: categorize(r) }));

// ---- TypeScript output ----
const tsLabels = mapped.map((r) => JSON.stringify(r.name)).join(",\n  ");
const tsCats = mapped
  .map((r) => (r.category ? JSON.stringify(r.category) : "null"))
  .join(", ");
const ts = `// AUTO-GENERATED by scripts/gen-yamnet-map.js — do not edit by hand.
// Maps YAMNet's 521 AudioSet classes to Tactiq alert categories.
import type { SoundCategory } from "./soundClassifier";

export const YAMNET_LABELS: readonly string[] = [
  ${tsLabels},
];

export const YAMNET_CATEGORY: readonly (SoundCategory | null)[] = [
  ${tsCats},
];
`;
fs.writeFileSync(path.join(ROOT, "lib", "yamnetMap.ts"), ts);

// ---- Kotlin output (Wear OS uses label strings from TFLite metadata) ----
const ktEntries = mapped
  .filter((r) => r.category)
  .map((r) => `        ${JSON.stringify(r.name.toLowerCase())} to ${JSON.stringify(r.category)}`)
  .join(",\n");
const kt = `// AUTO-GENERATED by scripts/gen-yamnet-map.js — do not edit by hand.
package com.tactiq.wear

object YamnetMap {
    /** YAMNet display-name (lowercased) → Tactiq category. Unlisted classes are ambient. */
    val byLabel: Map<String, String> = mapOf(
${ktEntries}
    )
}
`;
const ktDir = path.join(ROOT, "android", "wear", "src", "main", "java", "com", "tactiq", "wear");
fs.mkdirSync(ktDir, { recursive: true });
fs.writeFileSync(path.join(ktDir, "YamnetMap.kt"), kt);

// ---- Report ----
const counts = {};
for (const r of mapped) counts[r.category ?? "(ambient)"] = (counts[r.category ?? "(ambient)"] ?? 0) + 1;
console.log("Class distribution:", counts);
for (const cat of ["alarm", "doorbell", "baby_cry", "dog_bark", "loud_noise"]) {
  console.log(
    `${cat}:`,
    mapped.filter((r) => r.category === cat).map((r) => r.name).join(" | "),
  );
}
